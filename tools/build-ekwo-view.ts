// build-ekwo-view.ts
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';

const root = new URL('../', import.meta.url);
const source = await readFile(new URL('vendor/ekwo/cloud-captured.js', root), 'utf8');
const manifest = JSON.parse(await readFile(new URL('vendor/ekwo/manifest.json', root), 'utf8'));
assert.equal(createHash('sha256').update(source).digest('hex'), manifest.sha256);
const start = source.lastIndexOf('xB(window),zA(window),DQ(window),MJ(window);');
const menuStart = source.indexOf(':p.map(t=>{', source.indexOf('function ER(')) + 1;
const menuEnd = source.indexOf('}),o===void 0||r===null?', menuStart);
assert(start > 0 && menuStart > 0 && menuEnd > menuStart, 'Pinned native signatures changed');
const menu = source.slice(menuStart, menuEnd);
const bridge = await readFile(new URL('src/ekwo-bridge.js', root), 'utf8');
assert(bridge.includes('NATIVE_MENU_EXPRESSION'));
const generated = '// ekwo-view-runtime.js — generated by tools/build-ekwo-view.ts\n' +
  source.slice(0, start) + bridge.replace('NATIVE_MENU_EXPRESSION', menu);
const target = new URL('ekwo-view-runtime.js', root);
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), generated);
else await writeFile(target, generated);
console.log('PASS: pinned Ekwo form/menu bridge ' + (process.argv.includes('--check') ? 'verified' : 'built'));
